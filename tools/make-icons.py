#!/usr/bin/env python3
"""Generate the Travel Atlas app icons.

    python3 tools/make-icons.py          (needs Pillow)

One set of geometry (below, in a 512x512 design space) is the single source of truth:
the script writes the SVG sources (icons/icon.svg, icons/icon-maskable.svg) from it and
rasterises the PNGs from the same numbers with Pillow, 4x supersampled.

  icon.svg           -> icon-192.png, icon-512.png          rounded square, transparent corners
  icon-maskable.svg  -> icon-maskable-512.png, apple-touch-icon.png (180)
                        full-bleed background, art scaled to 0.9 about the centre so the
                        globe (outer radius 175 * 0.9 = 158) sits inside the 204.8 safe zone.

The mark is original: a globe outline (two meridians, equator, two parallels) on dark
#1b2229 with one abstract amber #e28a2b landmass.
"""
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
ICONS = ROOT / "icons"

# ---- geometry (512 design units) -------------------------------------------------
BG = "#1b2229"
OCEAN = "#24303a"
AMBER = "#e28a2b"
LINE = "#e8eef2"
GRID_OPACITY = 0.5
CX = CY = 256
R = 168            # globe radius
RING_W = 14        # outer ring stroke
GRID_W = 8         # grid stroke
MERIDIAN_RX = 72   # inner meridian ellipse
CORNER = 112       # rounded-square radius (regular icon)
MASKABLE_SCALE = 0.9

# Abstract landmass: start point + cubic segments (c1, c2, end).
BLOB_START = (188, 168)
BLOB = [
    ((228, 140), (302, 150), (322, 190)),
    ((338, 222), (306, 244), (314, 276)),
    ((322, 310), (290, 346), (254, 338)),
    ((224, 331), (232, 296), (204, 284)),
    ((170, 270), (150, 238), (160, 206)),
    ((165, 190), (174, 177), (188, 168)),
]
# Parallels: quadratic curves (start, control, end).
PARALLELS = [((100, 176), (256, 206), (412, 176)), ((100, 336), (256, 306), (412, 336))]


# ---- SVG output -------------------------------------------------------------------
def p(pt):
    return f"{pt[0]:g} {pt[1]:g}"


def art_svg(indent):
    blob = f"M{p(BLOB_START)}" + "".join(f"C{p(a)} {p(b)} {p(c)}" for a, b, c in BLOB) + "Z"
    par = "".join(f"M{p(a)}Q{p(b)} {p(c)}" for a, b, c in PARALLELS)
    lines = [
        "<defs>",
        f'  <clipPath id="globe"><circle cx="{CX}" cy="{CY}" r="{R}"/></clipPath>',
        "</defs>",
        '<g clip-path="url(#globe)">',
        f'  <circle cx="{CX}" cy="{CY}" r="{R}" fill="{OCEAN}"/>',
        f'  <path fill="{AMBER}" d="{blob}"/>',
        f'  <g fill="none" stroke="{LINE}" stroke-opacity="{GRID_OPACITY:g}" stroke-width="{GRID_W}">',
        f'    <ellipse cx="{CX}" cy="{CY}" rx="{MERIDIAN_RX}" ry="{R}"/>',
        f'    <line x1="{CX}" y1="{CY - R}" x2="{CX}" y2="{CY + R}"/>',
        f'    <line x1="{CX - R - 8}" y1="{CY}" x2="{CX + R + 8}" y2="{CY}"/>',
        f'    <path d="{par}"/>',
        "  </g>",
        "</g>",
        f'<circle cx="{CX}" cy="{CY}" r="{R}" fill="none" stroke="{LINE}" stroke-width="{RING_W}"/>',
    ]
    return "\n".join(indent + l for l in lines)


def write_svgs():
    head = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">\n  <title>Travel Atlas</title>\n'
    gen = "  <!-- Generated by tools/make-icons.py; edit the geometry there. -->\n"
    (ICONS / "icon.svg").write_text(
        head + gen + f'  <rect width="512" height="512" rx="{CORNER}" fill="{BG}"/>\n' + art_svg("  ") + "\n</svg>\n"
    )
    s = f"{MASKABLE_SCALE:g}"
    (ICONS / "icon-maskable.svg").write_text(
        head + gen + f'  <rect width="512" height="512" fill="{BG}"/>\n'
        f'  <g transform="translate({CX} {CY}) scale({s}) translate(-{CX} -{CY})">\n'
        + art_svg("    ") + "\n  </g>\n</svg>\n"
    )


# ---- raster output ----------------------------------------------------------------
def cubic(p0, p1, p2, p3, n=40):
    out = []
    for i in range(1, n + 1):
        t = i / n
        u = 1 - t
        out.append(tuple(u**3 * a + 3 * u * u * t * b + 3 * u * t * t * c + t**3 * d for a, b, c, d in zip(p0, p1, p2, p3)))
    return out


def quad(p0, p1, p2, n=60):
    pts = [p0]
    for i in range(1, n + 1):
        t = i / n
        u = 1 - t
        pts.append(tuple(u * u * a + 2 * u * t * b + t * t * c for a, b, c in zip(p0, p1, p2)))
    return pts


def hex_rgba(h, a=255):
    h = h.lstrip("#")
    return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), a)


def render(size, maskable):
    ss = 4
    S = size * ss
    k = S / 512.0
    scale = MASKABLE_SCALE if maskable else 1.0

    def tx(pt):  # design units -> pixels, including maskable scaling about centre
        return ((CX + (pt[0] - CX) * scale) * k, (CY + (pt[1] - CY) * scale) * k)

    def L(v):  # length
        return v * scale * k

    img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if maskable:
        d.rectangle([0, 0, S, S], fill=hex_rgba(BG))
    else:
        d.rounded_rectangle([0, 0, S - 1, S - 1], radius=CORNER * k, fill=hex_rgba(BG))

    cx, cy = tx((CX, CY))
    r = L(R)
    box = [cx - r, cy - r, cx + r, cy + r]

    # Globe interior (ocean + land + grid), clipped to the globe circle.
    globe = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    g = ImageDraw.Draw(globe)
    g.ellipse(box, fill=hex_rgba(OCEAN))
    pts = [tx(BLOB_START)]
    cur = BLOB_START
    for c1, c2, end in BLOB:
        pts += [tx(q) for q in cubic(cur, c1, c2, end)]
        cur = end
    g.polygon(pts, fill=hex_rgba(AMBER))

    grid = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    gd = ImageDraw.Draw(grid)
    gw = max(1, round(L(GRID_W)))
    rx = L(MERIDIAN_RX)
    gd.ellipse([cx - rx, cy - r, cx + rx, cy + r], outline=hex_rgba(LINE), width=gw)
    gd.line([tx((CX, CY - R)), tx((CX, CY + R))], fill=hex_rgba(LINE), width=gw)
    gd.line([tx((CX - R - 8, CY)), tx((CX + R + 8, CY))], fill=hex_rgba(LINE), width=gw)
    for a, b, c in PARALLELS:
        gd.line([tx(q) for q in quad(a, b, c)], fill=hex_rgba(LINE), width=gw, joint="curve")
    # Uniform group opacity (overlaps don't double up), like SVG stroke-opacity on one stroke.
    alpha = grid.getchannel("A").point(lambda v: round(v * GRID_OPACITY))
    grid.putalpha(alpha)
    globe = Image.alpha_composite(globe, grid)

    clip = Image.new("L", (S, S), 0)
    ImageDraw.Draw(clip).ellipse(box, fill=255)
    globe.putalpha(ImageChops.multiply(globe.getchannel("A"), clip))
    img = Image.alpha_composite(img, globe)

    # Outer ring, centred on the circle edge like an SVG stroke.
    d = ImageDraw.Draw(img)
    hw = L(RING_W) / 2
    d.ellipse([cx - r - hw, cy - r - hw, cx + r + hw, cy + r + hw], outline=hex_rgba(LINE), width=round(L(RING_W)))

    return img.resize((size, size), Image.LANCZOS)


def main():
    ICONS.mkdir(exist_ok=True)
    write_svgs()
    jobs = [
        ("icon-192.png", 192, False),
        ("icon-512.png", 512, False),
        ("icon-maskable-512.png", 512, True),
        ("apple-touch-icon.png", 180, True),
    ]
    for name, size, maskable in jobs:
        im = render(size, maskable)
        if maskable:  # fully opaque; iOS and maskable consumers expect no transparency
            im = im.convert("RGB")
        im.save(ICONS / name, optimize=True)
        print(f"{name}  {size}x{size}")


if __name__ == "__main__":
    main()
