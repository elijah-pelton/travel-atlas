#!/usr/bin/env node
// Builds worker/place-ids.js: the allowlist of every place id the sync API accepts.
// Source of truth is the map data the app draws: data/na.json (places, insets[].id, insets[].places)
// and data/world.json (places). Run after changing either file:
//   node tools/make-place-ids.mjs          write worker/place-ids.js
//   node tools/make-place-ids.mjs --check  exit 1 if worker/place-ids.js is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(REPO, 'worker', 'place-ids.js');

export function collectIds() {
  const na = JSON.parse(readFileSync(path.join(REPO, 'data', 'na.json'), 'utf8'));
  const world = JSON.parse(readFileSync(path.join(REPO, 'data', 'world.json'), 'utf8'));
  const ids = new Set();
  const add = (id) => {
    if (typeof id !== 'string' || !/^[A-Z0-9-]{2,7}$/.test(id)) throw new Error(`odd place id in data: ${JSON.stringify(id)}`);
    ids.add(id);
  };
  for (const p of na.places || []) add(p.id);
  for (const ins of na.insets || []) {
    if (ins.id) add(ins.id); // the app registers the inset's own id too (js/app.js)
    for (const p of ins.places || []) add(p.id);
  }
  for (const p of world.places || []) add(p.id);
  return [...ids].sort();
}

export function render(ids) {
  return [
    '// GENERATED by tools/make-place-ids.mjs from data/na.json and data/world.json. Do not edit by hand;',
    '// run `node tools/make-place-ids.mjs` after changing the map data (`--check` verifies it is current).',
    `// ${ids.length} place ids. The sync API rejects any other id with 400.`,
    'const ids = new Set([',
    ...ids.map((id) => `  '${id}',`),
    ']);',
    "for (const m of ['add', 'delete', 'clear']) {",
    "  ids[m] = () => {",
    "    throw new TypeError('PLACE_IDS is read-only');",
    '  };',
    '}',
    'export const PLACE_IDS = Object.freeze(ids);',
    '',
  ].join('\n');
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const want = render(collectIds());
  if (process.argv.includes('--check')) {
    let have = '';
    try {
      have = readFileSync(OUT, 'utf8');
    } catch {}
    if (have !== want) {
      console.error('worker/place-ids.js is out of date: run `node tools/make-place-ids.mjs`.');
      process.exit(1);
    }
    console.log('worker/place-ids.js is up to date.');
  } else {
    writeFileSync(OUT, want);
    console.log(`wrote ${path.relative(REPO, OUT)}`);
  }
}
