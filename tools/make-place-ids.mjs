#!/usr/bin/env node
// Builds worker/place-ids.js: the allowlist of every place id the sync API accepts.
// Sources of truth:
//   - the map data the app draws: data/na.json (places, insets[].id, insets[].places) and
//     data/world.json (places);
//   - data/cities-ids.json (written by tools/make-cities.py): the sorted list of every city id
//     ever published (`C-<ne_id>`), including retired/remapped ones, so a stale id on some device
//     stays accepted. Optional: without the file the allowlist has no cities.
// Run after changing any of them:
//   node tools/make-place-ids.mjs          write worker/place-ids.js
//   node tools/make-place-ids.mjs --check  exit 1 if worker/place-ids.js is out of date
// The output is compact (space-separated ids in a few long lines), not one id per line.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(REPO, 'worker', 'place-ids.js');
const CITIES = path.join(REPO, 'data', 'cities-ids.json');

// Keep these two in step with the copies rendered into worker/place-ids.js below.
export const AREA_ID_RE = /^[A-Z]{2,3}(?:-[A-Z]{2,3})?$/; // FRA, KOS, US-CA, CA-ON, US-PRI
export const CITY_ID_RE = /^C-\d{1,12}$/; // C-<Natural Earth ne_id>

export function collectAreaIds() {
  const na = JSON.parse(readFileSync(path.join(REPO, 'data', 'na.json'), 'utf8'));
  const world = JSON.parse(readFileSync(path.join(REPO, 'data', 'world.json'), 'utf8'));
  const ids = new Set();
  const add = (id) => {
    if (typeof id !== 'string' || !AREA_ID_RE.test(id)) throw new Error(`odd place id in data: ${JSON.stringify(id)}`);
    ids.add(id);
  };
  for (const p of na.places || []) add(p.id);
  for (const ins of na.insets || []) {
    if (ins.id) add(ins.id); // the app registers the inset's own id too (js/app.js)
    for (const p of ins.places || []) add(p.id);
  }
  for (const p of world.places || []) add(p.id);
  return [...ids].sort();
}

export function collectCityIds() {
  if (!existsSync(CITIES)) return [];
  const list = JSON.parse(readFileSync(CITIES, 'utf8'));
  if (!Array.isArray(list)) throw new Error('data/cities-ids.json must be a JSON array of "C-<ne_id>" strings');
  const ids = new Set();
  for (const id of list) {
    if (typeof id !== 'string' || !CITY_ID_RE.test(id)) throw new Error(`odd city id in data/cities-ids.json: ${JSON.stringify(id)}`);
    ids.add(id);
  }
  return [...ids].sort();
}

// Back-compat name: every id (areas, then cities).
export function collectIds() {
  return [...collectAreaIds(), ...collectCityIds()];
}

// Space-separated words wrapped at ~100 columns, as the body of a template literal.
function wrap(words) {
  const lines = [];
  let line = '';
  for (const w of words) {
    if (line && line.length + 1 + w.length > 100) {
      lines.push(line);
      line = w;
    } else line = line ? `${line} ${w}` : w;
  }
  if (line) lines.push(line);
  return lines.join('\n');
}

export function render(areas, cities = []) {
  const nums = cities.map((id) => id.slice(2));
  return [
    '// GENERATED by tools/make-place-ids.mjs from data/na.json, data/world.json and data/cities-ids.json.',
    '// Do not edit by hand; run `node tools/make-place-ids.mjs` after changing the map or city data',
    '// (`--check` verifies it is current).',
    `// ${areas.length} map places + ${cities.length} cities = ${areas.length + cities.length} ids.`,
    '// The sync API rejects malformed ids with 400 and drops well-formed ids that are not listed here.',
    '',
    '// Well-formed id shapes (worker/model.js): map places, and cities `C-<Natural Earth ne_id>`.',
    `export const AREA_ID_RE = ${AREA_ID_RE};`,
    `export const CITY_ID_RE = ${CITY_ID_RE};`,
    '',
    'const AREAS = `',
    wrap(areas),
    '`;',
    '',
    "// City ids without their 'C-' prefix.",
    'const CITIES = `',
    wrap(nums),
    '`;',
    '',
    'const words = (s) => s.split(/\\s+/).filter(Boolean);',
    'const ids = new Set(words(AREAS));',
    "for (const n of words(CITIES)) ids.add('C-' + n);",
    "for (const m of ['add', 'delete', 'clear']) {",
    '  ids[m] = () => {',
    "    throw new TypeError('PLACE_IDS is read-only');",
    '  };',
    '}',
    'export const PLACE_IDS = Object.freeze(ids);',
    `export const AREA_COUNT = ${areas.length};`,
    `export const CITY_COUNT = ${cities.length};`,
    '',
  ].join('\n');
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const areas = collectAreaIds();
  const cities = collectCityIds();
  const want = render(areas, cities);
  if (process.argv.includes('--check')) {
    let have = '';
    try {
      have = readFileSync(OUT, 'utf8');
    } catch {}
    if (have !== want) {
      console.error('worker/place-ids.js is out of date: run `node tools/make-place-ids.mjs`.');
      process.exit(1);
    }
    console.log(`worker/place-ids.js is up to date (${areas.length} places, ${cities.length} cities).`);
  } else {
    writeFileSync(OUT, want);
    console.log(`wrote ${path.relative(REPO, OUT)} (${areas.length} places, ${cities.length} cities, ${want.length} bytes)`);
  }
}
